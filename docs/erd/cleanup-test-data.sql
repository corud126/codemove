-- ============================================================
-- 테스트 데이터 정리 (Oracle 11g XE)
-- 테스트 고객(휴대폰 010-0000-0001)으로 만든 견적 요청 · 견적서 · 예약 · 후기 · 채팅 · 알림을 지운다.
-- 테스트 계정(고객 · 관리자 admin)은 남겨 두고 계속 쓴다. 화면 점검이 끝날 때마다 실행.
-- 지우는 순서는 외래키 순서 (자식 → 부모). 마지막에 COMMIT.
--
-- 업로드 파일(영상 · 후기 사진)은 DB 에서만 지워지므로, 아래 첫 SELECT 로 경로를 확인해 파일도 함께 지운다.
-- ============================================================

-- 0. 지울 파일 경로 확인 (영상 · 후기 사진)
SELECT V.FILE_PATH
  FROM TBL_RE_VIDEO V
  JOIN TBL_MOVE_REQUEST R ON R.REQUEST_ID = V.REQUEST_ID
 WHERE R.MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')
UNION ALL
SELECT P.FILE_PATH
  FROM TBL_REVIEW_PHOTO P
  JOIN TBL_REVIEW RV ON RV.REVIEW_ID = P.REVIEW_ID
  JOIN TBL_RESERVATION RS ON RS.RESERVATION_ID = RV.RESERVATION_ID
  JOIN TBL_MOVE_REQUEST R ON R.REQUEST_ID = RS.REQUEST_ID
 WHERE R.MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001');

-- 1. 후기
DELETE FROM TBL_REVIEW_PHOTO
 WHERE REVIEW_ID IN (SELECT RV.REVIEW_ID FROM TBL_REVIEW RV
                       JOIN TBL_RESERVATION RS ON RS.RESERVATION_ID = RV.RESERVATION_ID
                       JOIN TBL_MOVE_REQUEST R ON R.REQUEST_ID = RS.REQUEST_ID
                      WHERE R.MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));
DELETE FROM TBL_REVIEW
 WHERE RESERVATION_ID IN (SELECT RS.RESERVATION_ID FROM TBL_RESERVATION RS
                            JOIN TBL_MOVE_REQUEST R ON R.REQUEST_ID = RS.REQUEST_ID
                           WHERE R.MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));

-- 2. 예약
DELETE FROM TBL_RESERVATION
 WHERE REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                       WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));

-- 3. 견적서 (요청으로 만든 견적 + 회원을 연결해 등록한 사진·PDF 견적)
DELETE FROM TBL_QUOTE_ITEM
 WHERE QUOTE_ID IN (SELECT QUOTE_ID FROM TBL_QUOTE
                     WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')
                        OR REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                                           WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')));
DELETE FROM TBL_QUOTE_OPTION
 WHERE QUOTE_ID IN (SELECT QUOTE_ID FROM TBL_QUOTE
                     WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')
                        OR REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                                           WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')));
DELETE FROM TBL_QUOTE
 WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001')
    OR REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                       WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));

-- 4. 견적 요청
DELETE FROM TBL_REQUEST_ITEM
 WHERE REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                       WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));
DELETE FROM TBL_RE_VIDEO
 WHERE REQUEST_ID IN (SELECT REQUEST_ID FROM TBL_MOVE_REQUEST
                       WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));
DELETE FROM TBL_MOVE_REQUEST
 WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001');

-- 5. 채팅
DELETE FROM TBL_CHAT_MESSAGE
 WHERE ROOM_ID IN (SELECT ROOM_ID FROM TBL_CHAT_ROOM
                    WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001'));
DELETE FROM TBL_CHAT_ROOM
 WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001');

-- 6. 알림 (고객이 받은 알림 + 이 고객 관련 관리자 알림)
DELETE FROM TBL_NOTIFICATION
 WHERE MEMBER_ID IN (SELECT MEMBER_ID FROM TBL_MEMBER WHERE PHONE = '010-0000-0001');

COMMIT;
